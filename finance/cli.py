"""Command line interface.

Three commands, matching the three things this repo does:

``build``   regenerate ``ledger/<slug>/generated.beancount`` from raw exports plus rules
``review``  print the transactions no rule claimed — the queue an agent works through
``check``   validate with ``bean-check`` and report the transfer clearing account
``prices``  turn a Delta portfolio snapshot into price directives

``review`` is the only AI touchpoint, and it is deliberately a *report*: an agent reads it,
edits the rules file, and re-runs ``build``. No transaction is ever sent to a model.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
from collections import defaultdict
from collections.abc import Iterable
from datetime import date as Date
from datetime import timedelta
from decimal import Decimal, InvalidOperation
from pathlib import Path
from typing import NamedTuple

from finance import config as config_module
from finance.dedup import dedupe, dedupe_directives, duplicate_report
from finance.models import Balance, Directive, Transaction, posting_amounts
from finance.parsers import FORMATS, UnknownAccountError
from finance.prices import match
from finance.prices import render as render_prices
from finance.render import render
from finance.rules import Ruleset, movement, needs_rule

#: A transfer leg younger than this may simply not have settled yet.
SETTLEMENT_DAYS = 5


def _read_sources(cfg: config_module.LedgerConfig) -> list[Directive]:
    directives: list[Directive] = []
    for source in cfg.sources:
        parser = FORMATS.get(source.format)
        if parser is None:
            raise SystemExit(
                f"unknown format {source.format!r} for {source.path}; "
                f"known formats: {', '.join(sorted(FORMATS))}"
            )
        directives.extend(parser(source.path, cfg.ruleset.own_accounts))
    return directives


def _split(directives: Iterable[Directive]) -> tuple[list[Transaction], list[Directive]]:
    transactions, others = [], []
    for directive in directives:
        if isinstance(directive, Transaction):
            transactions.append(directive)
        else:
            others.append(directive)
    return transactions, others


class Parsed(NamedTuple):
    cfg: config_module.LedgerConfig
    raw: list[Transaction]
    """Every transaction read, before deduplication — needed to report what was dropped."""
    transactions: list[Transaction]
    others: list[Directive]


def _load(slug: str) -> Parsed:
    cfg = config_module.load(slug)
    try:
        directives = _read_sources(cfg)
    except UnknownAccountError as error:
        raise SystemExit(f"error: {error}") from None
    raw, others = _split(directives)
    return Parsed(cfg=cfg, raw=raw, transactions=dedupe(raw), others=dedupe_directives(others))


def cmd_build(slug: str) -> int:
    cfg, raw, transactions, others = _load(slug)

    resolved = [cfg.ruleset.resolve(txn) for txn in transactions]
    unclaimed = sum(
        1 for txn in transactions if needs_rule(txn) and not cfg.ruleset.classify(txn).matched
    )

    header = (
        "Generated by `finance build` — do not edit.\n"
        "Regenerate from the raw exports instead; hand edits are lost on the next build.\n"
        f"ledger: {slug}    transactions: {len(resolved)}    sources: {len(cfg.sources)}"
    )
    text = render([*resolved, *others], header=header)

    cfg.output_dir.mkdir(parents=True, exist_ok=True)
    cfg.generated_path.write_text(text, encoding="utf-8")

    print(f"wrote {cfg.generated_path} ({len(resolved)} transactions, {len(others)} other)")

    dropped = duplicate_report(raw)
    if dropped:
        print(
            f"  deduplicated {sum(dropped.values())} of {len(raw)} transactions "
            f"across {len(dropped)} overlapping files"
        )
    if unclaimed:
        print(
            f"  {unclaimed} transactions fell through to {cfg.ruleset.fallback_account} "
            f"— run `finance review {slug}`"
        )
    return 0


def cmd_review(slug: str, limit: int) -> int:
    cfg, _, transactions, _ = _load(slug)

    groups: dict[str, list[Transaction]] = defaultdict(list)
    for txn in transactions:
        if needs_rule(txn) and not cfg.ruleset.classify(txn).matched:
            groups[txn.payee or txn.narration or "(no payee)"].append(txn)

    if not groups:
        print(f"nothing unmatched in {slug} — every transaction is claimed by a rule")
        return 0

    def total(items: list[Transaction]) -> Decimal:
        return sum((p.units.number for t in items for p in t.postings if p.units), start=Decimal(0))

    ranked = sorted(groups.items(), key=lambda kv: abs(total(kv[1])), reverse=True)

    print(f"{len(groups)} unmatched payees in {slug}, largest absolute total first:\n")
    print(f"{'total':>12}  {'n':>4}  payee")
    print(f"{'-' * 12}  {'-' * 4}  {'-' * 60}")
    for payee, items in ranked[:limit]:
        print(f"{total(items):>12}  {len(items):>4}  {payee[:60]}")

    if len(ranked) > limit:
        print(f"\n... and {len(ranked) - limit} more (use --limit to see them)")

    print(f"\nAdd rules to {config_module.config_path(slug)}, then re-run `finance build {slug}`.")
    return 0


def _mask(identifier: str) -> str:
    """Shorten an account identifier for display, keeping it recognizable."""
    compact = identifier.replace(" ", "")
    return f"{compact[:5]}…{compact[-3:]}" if len(compact) > 9 else compact


#: A posting line in a Beancount file: an account, an amount, a currency. Hand-written entries
#: and generated ones both use this shape, which is what makes scanning viable.
POSTING_LINE = re.compile(
    r"^\s+(?P<account>[A-Z][A-Za-z0-9:-]*)\s+(?P<number>-?[\d,.]+)\s+(?P<currency>[A-Z][A-Z0-9]*)\s*$"
)


def _manual_postings(path: Path, account: str) -> tuple[dict[str, Decimal], int]:
    """Sum the hand-written postings to ``account``, plus a count of lines it could not read.

    The clearing report is built from parsed exports, which is where the pairing logic lives —
    but a leg that no export contains can only be recovered by hand, and then the report goes
    on flagging it forever. A detector that cannot be satisfied is one people learn to ignore,
    which costs more than the check is worth.

    Scanned rather than parsed: beancount is not a dependency here, and a full parse would be a
    subprocess. The risk of a scanner is silence, so unreadable candidate lines are counted and
    surfaced rather than skipped quietly.
    """
    totals: dict[str, Decimal] = defaultdict(Decimal)
    unreadable = 0
    if not path.exists():
        return totals, unreadable

    for line in path.read_text(encoding="utf-8").splitlines():
        if account not in line or line.lstrip().startswith(";"):
            continue
        match = POSTING_LINE.match(line)
        if not match or match.group("account") != account:
            unreadable += 1
            continue
        try:
            totals[match.group("currency")] += Decimal(match.group("number").replace(",", ""))
        except InvalidOperation:
            unreadable += 1
    return totals, unreadable


def _transfer_report(
    ruleset: Ruleset,
    directives: Iterable[Directive],
    manual_path: Path | None = None,
) -> int:
    """Report the clearing account balance, which should net to zero once legs pair up.

    A bare total is not actionable — the useful question is always *which* counterparty is
    unpaired, so the breakdown is printed alongside it. Counterparties whose legs offset
    (both sides of an internal transfer imported) drop out on their own.
    """
    account = ruleset.transfer_account
    per_currency: dict[str, Decimal] = defaultdict(Decimal)
    per_route: dict[tuple[str, str], list] = defaultdict(lambda: [Decimal(0), 0])
    stale = 0
    cutoff = Date.today() - timedelta(days=SETTLEMENT_DAYS)

    for directive in directives:
        if not isinstance(directive, Transaction):
            continue
        for posting_account, amount in posting_amounts(directive):
            if posting_account != account:
                continue
            per_currency[amount.currency] += amount.number

            # Group by the *route*, not the counterparty. An internal transfer is reported
            # twice — once from each side, each naming the other as counterparty — so keying
            # on the counterparty alone splits a balanced pair into two scary-looking halves.
            own = next((a for a, _ in posting_amounts(directive) if a != account), "(unknown)")
            counterparty = str(directive.meta.get("counterparty_iban") or "")
            far = ruleset.account_for_identifier(counterparty) or _mask(counterparty or "(none)")
            route = " <-> ".join(sorted([str(own), str(far)]))

            entry = per_route[(route, amount.currency)]
            entry[0] += amount.number
            entry[1] += 1
            if directive.date <= cutoff:
                stale += 1

    # Legs recovered by hand count too. Without them the report keeps flagging a gap that has
    # already been closed, and the routes below cannot show it: a hand-written entry has no
    # counterparty metadata, so it belongs to no route.
    manual, unreadable = _manual_postings(manual_path, account) if manual_path else ({}, 0)
    combined = dict(per_currency)
    for currency, number in manual.items():
        combined[currency] = combined.get(currency, Decimal(0)) + number

    outstanding = {c: n for c, n in combined.items() if n != 0}
    if not outstanding:
        print(f"{account}: settles to zero")
        if manual:
            print("  (after hand-written entries; the exports alone do not settle)")
        return 0

    print(f"{account}: does NOT settle to zero")
    for currency, number in sorted(outstanding.items()):
        print(f"  {number} {currency}")
    if manual:
        print("  of which, from the exports / from hand-written entries:")
        for currency in sorted(set(per_currency) | set(manual)):
            generated = per_currency.get(currency, Decimal(0))
            by_hand = manual.get(currency, Decimal(0))
            print(f"    {generated:>12} / {by_hand:>12} {currency}")
    if unreadable:
        print(
            f"  NOTE {unreadable} line(s) naming {account} in {manual_path} could not be read,"
            f" so this total may be incomplete."
        )

    unpaired = sorted(
        ((route, cur, net, n) for (route, cur), (net, n) in per_route.items() if net != 0),
        key=lambda row: -abs(row[2]),
    )
    balanced = sum(1 for (_, _), (net, _) in per_route.items() if net == 0)
    if unpaired:
        width = max(len(route) for route, _, _, _ in unpaired)
        print(f"\n  unpaired routes ({balanced} balanced route(s) omitted):")
        for route, currency, net, count in unpaired:
            legs = "leg" if count == 1 else "legs"
            print(f"    {route:<{width}}  {net:>12} {currency}  ({count} {legs})")

    print(
        f"\n  A non-zero balance means a leg is missing or double-counted. Usual causes:\n"
        f"    - the counterparty's own export is not in `files`, so its leg never arrives\n"
        f"      (such a counterparty does not belong in own_accounts — post it straight to\n"
        f"      its asset account instead)\n"
        f"    - the pairing leg falls outside the exported date range\n"
        f"    - the transfer has not settled yet ({stale} "
        f"{'leg is' if stale == 1 else 'legs are'} older than {SETTLEMENT_DAYS} days)"
    )
    return 1


def _bean_check_command() -> list[str] | None:
    """How to invoke bean-check here.

    Beancount is not a dependency of this package — this repo only emits text — so prefer a
    bean-check already on PATH and otherwise let uv fetch one on demand.
    """
    if shutil.which("bean-check"):
        return ["bean-check"]
    if shutil.which("uvx"):
        return ["uvx", "--quiet", "--from", "beancount", "bean-check"]
    return None


def _direction_report(ruleset: Ruleset, transactions: list[Transaction]) -> None:
    """Report income rules that claimed money going out, and expense rules money coming in.

    Not an error: a refund legitimately reverses the income it came from, and a corrected
    charge reverses an expense, so both directions occur in a healthy ledger and blocking
    them would be wrong. It is a *review prompt*, in the same spirit as the clearing account
    — a rule matching against the flow of its own account is how a payment to a counterparty
    quietly becomes negative income, and the only thing that separates that from a genuine
    refund is reading it.

    A rule that should never do this can say so with ``direction:`` and stop appearing here.
    """
    groups: dict[tuple[str, str, str], list[Decimal]] = defaultdict(list)
    for txn in transactions:
        if not needs_rule(txn):
            continue
        match = ruleset.classify(txn)
        if match.rule is None or match.rule.direction is not None:
            continue
        amount = movement(txn)
        if amount is None or amount == 0:
            continue
        wrong_way = (match.account.startswith("Income:") and amount < 0) or (
            match.account.startswith("Expenses:") and amount > 0
        )
        if wrong_way:
            key = (match.account, match.rule.field, match.rule.regex.pattern)
            groups[key].append(amount)

    if not groups:
        return

    print("\nrules matching against their account's own direction (review, not an error):")
    for account, field, pattern in sorted(
        groups, key=lambda k: sum(map(abs, groups[k])), reverse=True
    )[:10]:
        amounts = groups[(account, field, pattern)]
        total = sum(amounts, Decimal(0))
        shown = pattern if len(pattern) <= 48 else pattern[:47] + "…"
        print(f"  {total:>12} over {len(amounts):>4} row(s)  -> {account}")
        print(f"    {field} ~ {shown}")
    print("  Add `direction: in` (or `out`) to a rule that should never match the other way.")


def cmd_check(slug: str) -> int:
    cfg, _, transactions, others = _load(slug)
    resolved = [cfg.ruleset.resolve(txn) for txn in transactions]

    status = 0
    command = _bean_check_command()
    if not cfg.main_path.exists():
        print(f"note: {cfg.main_path} does not exist yet, skipping bean-check")
    elif command is None:
        print("note: neither bean-check nor uvx found, skipping validation")
    else:
        result = subprocess.run(  # noqa: S603 - fixed argv, no shell
            [*command, str(cfg.main_path)], capture_output=True, text=True
        )
        if result.returncode == 0:
            print(f"bean-check: {cfg.main_path} is valid")
        else:
            print(f"bean-check failed:\n{result.stdout}{result.stderr}".rstrip())
            status = 1

    balances = [d for d in others if isinstance(d, Balance)]
    print(f"balance assertions emitted: {len(balances)}")

    _direction_report(cfg.ruleset, transactions)
    return _transfer_report(cfg.ruleset, resolved, cfg.manual_path) or status


def cmd_prices(slug: str, snapshot: str, as_of: Date | None, portfolio: str) -> int:
    """Write price directives from a Delta snapshot an agent fetched over MCP.

    Deliberately takes a file rather than calling anything: no build step may depend on a
    network service or a model, so the fetch happens outside and only the text lands here.
    """
    cfg, _, transactions, _ = _load(slug)
    resolved = [cfg.ruleset.resolve(txn) for txn in transactions]

    holdings: dict[str, Decimal] = defaultdict(Decimal)
    names: dict[str, str] = {}
    for txn in resolved:
        for posting in txn.postings:
            if posting.units and posting.units.currency not in ("EUR", "USD", "JPY", "GBP"):
                holdings[posting.units.currency] += posting.units.number
                if txn.meta.get("product"):
                    names.setdefault(posting.units.currency, str(txn.meta["product"]))
    open_holdings = {c: q for c, q in holdings.items() if q != 0}

    assets = json.loads(Path(snapshot).read_text(encoding="utf-8")).get("assets", [])
    quotes, unpriced = match(open_holdings, names, assets)

    path = cfg.output_dir / "prices.beancount"
    path.write_text(
        render_prices(quotes, unpriced, as_of=as_of or Date.today(), portfolio=portfolio),
        encoding="utf-8",
    )
    print(f"wrote {path} ({len(quotes)} priced, {len(unpriced)} not)")
    for item in unpriced:
        print(f"  unpriced: {item.commodity:<14} {item.name[:40]:<40} ({item.reason})")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="finance", description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)

    build = sub.add_parser("build", help="regenerate the ledger from raw exports and rules")
    build.add_argument("ledger")

    review = sub.add_parser("review", help="list transactions no rule claimed")
    review.add_argument("ledger")
    review.add_argument("--limit", type=int, default=40)

    check = sub.add_parser("check", help="validate the ledger and the transfer clearing account")
    check.add_argument("ledger")

    prices = sub.add_parser("prices", help="write price directives from a Delta snapshot")
    prices.add_argument("ledger")
    prices.add_argument("snapshot", help="JSON as returned by Delta's get_portfolio")
    prices.add_argument("--as-of", type=Date.fromisoformat, default=None)
    prices.add_argument("--portfolio", default="Investments")

    args = parser.parse_args(argv)

    try:
        if args.command == "build":
            return cmd_build(args.ledger)
        if args.command == "review":
            return cmd_review(args.ledger, args.limit)
        if args.command == "check":
            return cmd_check(args.ledger)
        if args.command == "prices":
            return cmd_prices(args.ledger, args.snapshot, args.as_of, args.portfolio)
    except FileNotFoundError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2

    raise AssertionError(f"unhandled command {args.command!r}")


if __name__ == "__main__":
    sys.exit(main())
